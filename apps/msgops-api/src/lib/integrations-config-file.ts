import { mkdirSync, writeFileSync } from 'fs';
import { dirname } from 'path';
import { bmsConfigFilePath } from './bms-config-paths';

const HEADER = '# Generated by BMS. Do not edit manually — overwritten on each save.';

function writeEnvFile(path: string, lines: string[]): void {
  mkdirSync(dirname(path), { recursive: true });
  const content = [HEADER, '', ...lines].join('\n') + '\n';
  writeFileSync(path, content, 'utf8');
}

// ---------- S3 ----------

export interface S3SystemSettings {
  endpoint?: string;
  region?: string;
  bucket: string;
  accessKeyId: string;
  secretAccessKey: string;
  useObjectAcls?: boolean;
  assetsUrl?: string;
}

export function s3EnvFilePath(): string {
  return bmsConfigFilePath('s3.env');
}

export function writeS3EnvFile(dto: S3SystemSettings): void {
  const lines: string[] = [];
  if (dto.endpoint) lines.push(`S3_ENDPOINT=${dto.endpoint}`);
  if (dto.region) lines.push(`S3_REGION=${dto.region}`);
  lines.push(`S3_BUCKET=${dto.bucket}`);
  lines.push(`S3_ACCESS_KEY_ID=${dto.accessKeyId}`);
  lines.push(`S3_SECRET_ACCESS_KEY=${dto.secretAccessKey}`);
  if (dto.useObjectAcls === false) lines.push('S3_USE_OBJECT_ACLS=false');
  if (dto.assetsUrl) lines.push(`BMS_ASSETS_URL=${dto.assetsUrl}`);
  writeEnvFile(s3EnvFilePath(), lines);
}

