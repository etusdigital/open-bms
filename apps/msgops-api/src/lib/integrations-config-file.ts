// ---------- FCM ----------

export interface FcmSystemSettings {
  // Raw Google service-account JSON. Stored in DB as a structured value but
  // serialized to a single line in the env file so workers can parse it back.
  serviceAccountJson: string;
}

export function fcmEnvFilePath(): string {
  return bmsConfigFilePath('fcm.env');
}

export function writeFcmEnvFile(dto: FcmSystemSettings): void {
  // Validate JSON is parseable; throw early so we never write a corrupt env file.
  JSON.parse(dto.serviceAccountJson);
  // Collapse to single line (the file format is line-based; \n inside the
  // private_key is preserved as an escaped \n inside the JSON string).
  const oneLine = JSON.stringify(JSON.parse(dto.serviceAccountJson));
  writeEnvFile(fcmEnvFilePath(), [`FIREBASE_SERVICE_ACCOUNT=${oneLine}`]);
}

